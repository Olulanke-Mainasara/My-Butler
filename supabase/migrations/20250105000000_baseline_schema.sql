-- Baseline schema for the My Butler Supabase project.
--
-- This repo had no supabase/migrations directory until this file was added,
-- so the actual table-creation migrations were never tracked - the schema
-- was built directly in the Supabase dashboard/SQL editor. This file is a
-- best-effort reconstruction from live introspection (list_tables, a full
-- pg_policies dump, and pg_get_functiondef on every function), captured
-- immediately before the fix migrations that follow it were applied, so
-- history in this repo matches what actually happened to the live database.
--
-- Known gaps: this does not attempt to capture secondary indexes beyond
-- what's implied by PRIMARY KEY/UNIQUE constraints, since those weren't part
-- of what was introspected. The `customers_insert_notify` trigger's exact
-- attachment (assumed AFTER INSERT ON public.customers below) was not
-- re-verified before this file was written - confirm against the live
-- project before treating it as authoritative.
--
-- This file is NOT meant to be re-run against the live project (the tables
-- already exist there) - it exists so the schema is reviewable by reading
-- the repo, and so a fresh environment could be bootstrapped from it.

