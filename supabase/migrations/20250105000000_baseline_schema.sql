create or replace function public.toggle_bookmark(_target_id uuid, _target_type text)
returns text
language plpgsql
security definer
as $function$
declare
  existing_bookmark bookmarks%rowtype;
begin
  if auth.uid() is null then
    raise exception 'User must be authenticated';
  end if;

  -- BUG, fixed in 20260729172653_fix_toggle_bookmark_wrong_table_and_search_path.sql:
  -- operates on `cart`, which has no target_id/target_type columns, instead
  -- of `bookmarks` - every call throws "column target_id does not exist".
  select * into existing_bookmark
  from cart
  where user_id = auth.uid()
    and target_id = _target_id;

  if found then
    delete from cart
    where user_id = auth.uid()
      and target_id = _target_id;
    return 'removed';
  else
    insert into cart (user_id, target_id, target_type)
    values (auth.uid(), _target_id, _target_type);
    return 'added';
  end if;

exception
  when others then
    raise exception 'Error toggling bookmark: %', sqlerrm;
end;
$function$;

create or replace function public.toggle_cart(_item_id uuid, _quantity integer, _item_type text)
returns text
language plpgsql
security definer
as $function$
declare
  existing_cart_item cart%rowtype;
begin
  if auth.uid() is null then
    raise exception 'User must be authenticated';
  end if;

  select * into existing_cart_item
  from cart
  where user_id = auth.uid()
    and item_id = _item_id;

  if found then
    delete from cart
    where user_id = auth.uid()
      and item_id = _item_id;
    return 'removed';
  else
    insert into cart (user_id, item_id, item_type, quantity)
    values (auth.uid(), _item_id, _item_type, _quantity);
    return 'added';
  end if;

exception
  when others then
    raise exception 'Error toggling cart: %', sqlerrm;
end;
$function$;

